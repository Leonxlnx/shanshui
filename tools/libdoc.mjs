// Generate docs/LIBRARY.md from the element modules: each module's leading doc
// comment plus the signatures of everything it exports.
//   node tools/libdoc.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib.mjs';

const dir = path.join(ROOT, 'src', 'lib');
const order = ['brush', 'inkfx', 'pine', 'rock', 'peaks', 'atmos', 'water', 'architecture', 'fauna', 'flora', 'seal'];
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort((a, b) => order.indexOf(a.slice(0, -3)) - order.indexOf(b.slice(0, -3)));
let md = '# Element library\n\nGenerated by `node tools/libdoc.mjs` from the modules in `src/lib/`. Read the module itself for details; the lab scenes in `src/lab/<module>-*.js` show each element in use.\n';
for (const f of files) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8');
  const lines = src.split('\n');
  const head = [];
  for (const l of lines) {
    if (/^\s*(\/\/|\/\*|\*)/.test(l) || (head.length && l.trim() === '')) head.push(l.replace(/^\s*(\/\/ ?|\/\*\*? ?|\*\/|\* ?)/, '')); else break;
    if (head.length > 120) break;
  }
  const exps = [];
  lines.forEach((l, i) => {
    const m = /^export\s+(async\s+)?(function\*?|const|let|class)\s+([A-Za-z0-9_$]+)\s*(\([^)]*\)|=\s*\([^)]*\)\s*=>|=)?/.exec(l);
    if (m) exps.push(`- \`${m[3]}${m[2] === 'function' ? (m[4] || '()') : ''}\` (line ${i + 1})`);
    const r = /^export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/.exec(l);
    if (r) {
      const sub = path.join(dir, r[2]);
      const subSrc = fs.existsSync(sub) ? fs.readFileSync(sub, 'utf8').split('\n') : [];
      for (const name of r[1].split(',').map((x) => x.trim()).filter(Boolean)) {
        const k = subSrc.findIndex((x) => new RegExp(`^export\\s+(async\\s+)?(function|const|let|class)\\s+${name}\\b`).test(x));
        const sig = k >= 0 ? (/\(([^)]*)\)/.exec(subSrc[k]) || ['', ''])[0] : '';
        exps.push(`- \`${name}${sig}\` (from ${r[2]}${k >= 0 ? ':' + (k + 1) : ''})`);
      }
    }
  });
  const labs = fs.readdirSync(path.join(ROOT, 'src', 'lab')).filter((x) => x.startsWith(f.slice(0, -3) === 'architecture' ? 'arch-' : f.slice(0, -3) + '-'));
  md += `\n## ${f}  (${Math.round(src.length / 1024)} KB)\n\n${head.join('\n').trim()}\n\n**Exports**\n\n${exps.join('\n') || '(none)'}\n`;
  if (labs.length) md += `\n**Lab scenes:** ${labs.map((x) => '`lab/' + x.slice(0, -3) + '`').join(', ')}\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'LIBRARY.md'), md);
console.log('wrote docs/LIBRARY.md', md.length, 'chars');
